        private static readonly string[] Endings = new[]
        {
            "иями","ями","ами","ию","ью","ою","ею","ого","ему","ому","ыми","ими","ей","ов","ев",
            "ам","ям","ах","ях","ом","ем","ым","им","ую","юю","ая","яя","ое","ее","ые","ие",
            "ать","ить","еть","ять","ой","ый","ий","ь","й","ы","и","а","я","у","ю","о","е"
        };
        public static string Normalize(string value)
        {
            if (String.IsNullOrWhiteSpace(value)) return value ?? "";
            string semantic = EmojiSemanticText.Normalize(value);
            return String.Join(" ", Regex.Split(semantic.ToLowerInvariant().Replace('ё','е'), @"\s+")
                .Where(x => !String.IsNullOrWhiteSpace(x)).Select(NormalizeToken)).Trim();
        }
        public static IList<string> Tokens(string value)
        {
            return Regex.Split(Normalize(value), @"\s+").Where(x => !String.IsNullOrWhiteSpace(x)).ToList();
        }
        public static string Lemma(string value) { return NormalizeToken(value ?? ""); }
        private static string NormalizeToken(string raw)
        {
            string word = (raw ?? "").Trim().Trim('.',',',';',':','!','?','(',')','[',']','"','\'');
            if (word.Length == 0) return word;
            string known;
            if (Irregular.TryGetValue(word, out known)) return known;
            if (word.EndsWith("ся", StringComparison.Ordinal) || word.EndsWith("сь", StringComparison.Ordinal)) return word;
            if (word.Any(Char.IsDigit) || word.Any(c => c >= 'a' && c <= 'z')) return word;
            foreach (string ending in Endings)
                if (word.Length > ending.Length + 2 && word.EndsWith(ending, StringComparison.Ordinal))
                    return word.Substring(0, word.Length - ending.Length);
            return word;
        }
